-- 1. Create Sales Header Table (if not exists)
CREATE TABLE IF NOT EXISTS public.pharmacy_sales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name TEXT,
    customer_phone TEXT,
    patient_id TEXT, 
    doctor_name TEXT,
    payment_mode TEXT DEFAULT 'Cash',
    paid_amount_cash NUMERIC DEFAULT 0,
    paid_amount_online NUMERIC DEFAULT 0,
    subtotal NUMERIC NOT NULL DEFAULT 0,
    discount_amount NUMERIC DEFAULT 0,
    curr_total NUMERIC NOT NULL DEFAULT 0,
    status TEXT DEFAULT 'completed',
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT now()
);

-- 2. Create Sales Items Table (if not exists)
CREATE TABLE IF NOT EXISTS public.pharmacy_sale_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id BIGINT REFERENCES public.pharmacy_sales(id) ON DELETE CASCADE,
    inventory_id BIGINT, 
    medicine_id BIGINT,
    batch_number TEXT,
    expiry_date DATE,
    quantity NUMERIC NOT NULL, 
    quantity_mode TEXT DEFAULT 'Pack', 
    pack_size_quantity INTEGER DEFAULT 1, 
    total_units_sold INTEGER DEFAULT 0, 
    unit_price NUMERIC NOT NULL,
    total_price NUMERIC NOT NULL,
    discount_amount NUMERIC DEFAULT 0, -- Store item level discount
    created_at TIMESTAMPTZ DEFAULT now()
);

-- 3. Add discount_amount column if missing (Migration Step)
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM information_schema.columns
        WHERE table_name = 'pharmacy_sale_items'
        AND column_name = 'discount_amount'
    ) THEN
        ALTER TABLE public.pharmacy_sale_items ADD COLUMN discount_amount NUMERIC DEFAULT 0;
    END IF;
END $$;

